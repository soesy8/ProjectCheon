var root = GameObject.Find("HeightFog_VFX");
var fog = root.GetComponent<Cheon.World.HeightFogVolume>();
Undo.RecordObject(fog, "Adjust height fog area");
var settings = new SerializedObject(fog);
settings.FindProperty("areaSize").vector2Value = new Vector2(1000f, 1120f);
settings.FindProperty("edgeFade").floatValue = 180f;
settings.ApplyModifiedProperties();
fog.ApplySettings();
EditorUtility.SetDirty(fog);
var scene = root.scene;
UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(scene);
bool saved = UnityEditor.SceneManagement.EditorSceneManager.SaveScene(scene);
Selection.activeGameObject = root;
SceneView.RepaintAll();
var shader = root.GetComponentInChildren<MeshRenderer>().sharedMaterial.shader;
return new { saved, scene = scene.path, root.name, height = root.transform.position.y, children = root.transform.childCount, shaderErrors = ShaderUtil.GetShaderMessages(shader) };
