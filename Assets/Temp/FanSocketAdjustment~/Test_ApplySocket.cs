if (Application.isPlaying) throw new Exception("소켓 설정은 Edit Mode에서 저장해야 합니다.");
var scene = UnityEngine.SceneManagement.SceneManager.GetActiveScene();
if (scene.path != "Assets/Test/PlayerFanAnimation/Scenes/Test_PlayerFanAnimation.unity") throw new Exception("Expected player fan test scene");
var attachment = scene.GetRootGameObjects().SelectMany(r=>r.GetComponentsInChildren<Cheon.Testing.PlayerFan.Test_PlayerFanAttachment>(true)).Single();
var socket = attachment.HandSocket;
var settings = new SerializedObject(attachment);
var positionProperty = settings.FindProperty("socketLocalPosition");
var rotationProperty = settings.FindProperty("socketLocalEulerAngles");
Vector3 previousPosition = positionProperty.vector3Value;
Vector3 previousEuler = rotationProperty.vector3Value;
Vector3 nextPosition = previousPosition + new Vector3(-0.015f,0f,0f);
Vector3 nextEuler = previousEuler + new Vector3(0f,0f,12f);
Undo.IncrementCurrentGroup();
int undoGroup = Undo.GetCurrentGroup();
Undo.SetCurrentGroupName("Adjust fan hand socket outward");
Undo.RecordObjects(new UnityEngine.Object[]{attachment,socket},"Adjust fan hand socket outward");
// LateUpdate가 같은 값을 유지하도록 Transform과 장착 스크립트의 저장값을 함께 변경한다.
positionProperty.vector3Value=nextPosition;
rotationProperty.vector3Value=nextEuler;
settings.ApplyModifiedProperties();
socket.localPosition=nextPosition;
socket.localRotation=Quaternion.Euler(nextEuler);
var socketSerialized = new SerializedObject(socket);
var eulerHint = socketSerialized.FindProperty("m_LocalEulerAnglesHint");
if(eulerHint!=null) {eulerHint.vector3Value=nextEuler;socketSerialized.ApplyModifiedProperties();}
if(PrefabUtility.IsPartOfPrefabInstance(socket)) PrefabUtility.RecordPrefabInstancePropertyModifications(socket);
EditorUtility.SetDirty(attachment);
EditorUtility.SetDirty(socket);
UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(scene);
if(!UnityEditor.SceneManagement.EditorSceneManager.SaveScene(scene)) throw new Exception("Scene save failed");
Undo.CollapseUndoOperations(undoGroup);
var report = new {scene=scene.path,socket=socket.name,beforePosition=previousPosition.ToString("F6"),afterPosition=nextPosition.ToString("F6"),beforeEuler=previousEuler.ToString("F3"),afterEuler=nextEuler.ToString("F3"),sceneSaved=!scene.isDirty};
System.IO.File.WriteAllText("Assets/Temp/FanSocketAdjustment~/Test_Applied.json",Newtonsoft.Json.JsonConvert.SerializeObject(report,Newtonsoft.Json.Formatting.Indented));
return report;
