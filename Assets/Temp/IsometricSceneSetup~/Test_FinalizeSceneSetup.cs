if (EditorApplication.isPlaying) throw new System.InvalidOperationException("최종 확인은 편집 모드에서 수행합니다.");
Application.runInBackground = UnityEditor.SessionState.GetBool("IsometricSceneSetup_PreviousBackground", true);
UnityEditor.SessionState.EraseBool("IsometricSceneSetup_PreviousBackground");
var scene = UnityEngine.SceneManagement.SceneManager.GetActiveScene();
var isometric = UnityEngine.Object.FindFirstObjectByType<Cheon.Testing.MountainMap.Test_IsometricView>();
isometric.SendMessage("ActivateView");
UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(scene);
UnityEditor.SceneManagement.EditorSceneManager.SaveScene(scene);
var path = scene.path;
UnityEditor.SceneManagement.EditorSceneManager.OpenScene(path);
var player = UnityEngine.Object.FindFirstObjectByType<Cheon.Testing.MountainMap.Test_MountainPlayerMovement>();
var rig = GameObject.Find("Test_IsometricView");
var camera = Camera.main;
var follow = camera.GetComponent<Cheon.Testing.MountainMap.Test_MountainPlayerCamera>();
bool afterReload = rig != null && camera.orthographic && !follow.enabled;
rig.SetActive(false);
bool restoresAfterReload = !camera.orthographic && follow.enabled;
rig.SetActive(true);
bool reappliesAfterReload = camera.orthographic && !follow.enabled;
Selection.activeGameObject = rig;
scene = UnityEngine.SceneManagement.SceneManager.GetActiveScene();
UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(scene);
UnityEditor.SceneManagement.EditorSceneManager.SaveScene(scene);
var report = new { scene = scene.path, saved = !scene.isDirty, afterReload, restoresAfterReload, reappliesAfterReload, playerPosition = player.transform.position.ToString("F4"), cameraRotation = camera.transform.eulerAngles.ToString("F4"), scriptPath = AssetDatabase.GetAssetPath(MonoScript.FromMonoBehaviour(rig.GetComponent<Cheon.Testing.MountainMap.Test_IsometricView>())), backgroundRestored = Application.runInBackground };
System.IO.File.WriteAllText("Assets/Temp/IsometricSceneSetup~/Test_FinalVerification.json", Newtonsoft.Json.JsonConvert.SerializeObject(report, Newtonsoft.Json.Formatting.Indented));
return report;
