var player = UnityEngine.Object.FindFirstObjectByType<Cheon.Testing.MountainMap.Test_MountainPlayerMovement>();
var animation = player.AnimationControl;
var camera = Camera.main;
var rig = GameObject.Find("Test_IsometricView");
var isometric = rig.GetComponent<Cheon.Testing.MountainMap.Test_IsometricView>();
var body = player.GetComponent<CharacterController>();
var follow = camera.GetComponent<Cheon.Testing.MountainMap.Test_MountainPlayerCamera>();
var initialPosition = player.transform.position;
var initialRotation = camera.transform.rotation;
var failures = new System.Collections.Generic.List<string>();
if (!EditorApplication.isPlaying) failures.Add("Play 모드 아님");
if (!body.isGrounded) failures.Add("캐릭터 접지 실패");
if (Vector3.Distance(initialPosition, new Vector3(-18.7239f, 3.4795f, 100.8249f)) > 0.2f) failures.Add("시작 위치 이탈");
if (!camera.orthographic || follow.enabled) failures.Add("아이소메트릭 초기 적용 실패");
var defaultTimings = ScriptableObject.CreateInstance<Cheon.Testing.PlayerFan.Test_PlayerActionTimings>();
bool timingsMatch = JsonUtility.ToJson(defaultTimings) == JsonUtility.ToJson(animation.SavedTimings);
if (!timingsMatch) failures.Add("코드 타이밍 기본값과 저장값 불일치");
bool runtimeTimingsMatch = JsonUtility.ToJson(animation.RuntimeTimings) == JsonUtility.ToJson(animation.SavedTimings);
if (!runtimeTimingsMatch) failures.Add("실행 타이밍과 저장값 불일치");
UnityEngine.Object.DestroyImmediate(defaultTimings);
var defaultPlayback = ScriptableObject.CreateInstance<Cheon.Testing.PlayerFan.Test_PlayerPlaybackSettings>();
bool playbackMatch = JsonUtility.ToJson(defaultPlayback) == JsonUtility.ToJson(animation.SavedPlaybackSettings);
if (!playbackMatch) failures.Add("재생 기본값과 저장값 불일치");
UnityEngine.Object.DestroyImmediate(defaultPlayback);
var scalarMismatches = new System.Collections.Generic.List<string>();
var defaultObject = new GameObject("Test_DefaultInspection");
defaultObject.SetActive(false);
var defaultAnimation = defaultObject.AddComponent<Cheon.Testing.PlayerFan.Test_PlayerFanAnimationController>();
foreach (var field in typeof(Cheon.Testing.PlayerFan.Test_PlayerFanAnimationController).GetFields(System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance)) {
 if ((field.IsPublic || System.Attribute.IsDefined(field, typeof(SerializeField))) && (field.FieldType == typeof(float) || field.FieldType == typeof(int)) && !object.Equals(field.GetValue(defaultAnimation), field.GetValue(animation))) scalarMismatches.Add(field.Name);
}
UnityEngine.Object.DestroyImmediate(defaultObject);
if (scalarMismatches.Count != 0) failures.Add("애니메이션 수치 기본값 불일치");
rig.SetActive(false);
bool restored = !camera.orthographic && follow.enabled;
if (!restored) failures.Add("기존 시점 복원 실패");
rig.SetActive(true);
bool reenabled = camera.orthographic && !follow.enabled && Quaternion.Angle(initialRotation, camera.transform.rotation) < 0.01f;
if (!reenabled) failures.Add("아이소메트릭 재적용 실패");
var originalCameraPosition = camera.transform.position;
body.enabled = false;
player.transform.position = initialPosition + Vector3.right * 2f;
isometric.SendMessage("LateUpdate");
bool tracksPlayer = camera.transform.position.x > originalCameraPosition.x;
player.transform.position = initialPosition;
body.enabled = true;
isometric.SendMessage("ActivateView");
if (!tracksPlayer) failures.Add("캐릭터 추적 실패");
var movementView = new SerializedObject(player).FindProperty("view").objectReferenceValue;
if (movementView != camera.transform) failures.Add("이동 기준 카메라 연결 실패");
var report = new { playing = EditorApplication.isPlaying, frame = Time.frameCount, grounded = body.isGrounded, position = initialPosition.ToString("F4"), playerYaw = player.transform.eulerAngles.y, orthographic = camera.orthographic, cameraPitch = camera.transform.eulerAngles.x, cameraYaw = camera.transform.eulerAngles.y, cameraSize = camera.orthographicSize, timingsMatch, runtimeTimingsMatch, playbackMatch, scalarMismatches, restored, reenabled, tracksPlayer, failures };
System.IO.File.WriteAllText("Assets/Temp/IsometricSceneSetup~/Test_PlayVerification.json", Newtonsoft.Json.JsonConvert.SerializeObject(report, Newtonsoft.Json.Formatting.Indented));
return report;
