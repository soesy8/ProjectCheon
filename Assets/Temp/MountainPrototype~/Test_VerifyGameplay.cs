var game=UnityEngine.Object.FindFirstObjectByType<Cheon.Prototype.MountainPass.PassGameFlow>();
var player=game.Player.GetComponent<Cheon.Prototype.MountainPass.PassPlayerMovement>();
var animation=player.AnimationControl;
var boss=game.Boss;
var failures=new System.Collections.Generic.List<string>();
var checks=new System.Collections.Generic.List<object>();
System.Action<string,bool,object> record=(name,passed,value)=>{checks.Add(new{name,passed,value});if(!passed)failures.Add(name);};
System.Collections.IEnumerator Routine(){
 game.BeginJourney(); boss.enabled=false;
 yield return new WaitForSeconds(0.3f);
 record("start_grounded",player.GetComponent<CharacterController>().isGrounded,player.transform.position.ToString());
 game.PlayerHealth.TakeDamage(30f);game.Heal();
 record("healing",game.PlayerHealth.Current==100f && game.Flasks==2,new{health=game.PlayerHealth.Current,game.Flasks});
 game.TogglePause();float stopped=Time.time;
 yield return new WaitForSecondsRealtime(0.2f);
 record("pause",Time.time==stopped && !player.InputEnabled,Time.time-stopped);
 game.TogglePause();
 player.Teleport(new Vector3(15.75f,27.2f,25.1f),Quaternion.identity);
 yield return new WaitForSeconds(0.25f);
 record("shrine_checkpoint",game.ReachedShrine && game.Flasks==3,new{game.ReachedShrine,game.Flasks});
 game.BeginBossChallenge();boss.enabled=false;
 yield return new WaitForSeconds(1.5f);
 record("encounter",game.InEncounter && game.View.BossLocked,boss.State.ToString());
 player.Teleport(boss.transform.position+Vector3.forward*3.5f,Quaternion.Euler(0f,180f,0f));
 yield return new WaitForSeconds(0.2f);
 for(int attack=1;attack<=3;attack++){
  float before=boss.Health.Current;
  bool accepted=animation.TryPlayAttack(attack);
  yield return new WaitForSeconds(2.3f);
  float expected=attack==1?22f:attack==2?28f:40f;
  record("attack_"+attack,accepted && Mathf.Abs(before-boss.Health.Current-expected)<0.1f,new{accepted,damage=before-boss.Health.Current});
 }
 game.PlayerHealth.Restore();animation.PlayIdle();
 player.Teleport(boss.transform.position+Vector3.forward*6f,Quaternion.Euler(0f,180f,0f));
 boss.enabled=true;
 var attackMethod=typeof(Cheon.Prototype.MountainPass.PassBossController).GetMethod("BeginAttack",System.Reflection.BindingFlags.NonPublic|System.Reflection.BindingFlags.Instance);
 var countField=typeof(Cheon.Prototype.MountainPass.PassBossController).GetField("attackCount",System.Reflection.BindingFlags.NonPublic|System.Reflection.BindingFlags.Instance);
 countField.SetValue(boss,0);attackMethod.Invoke(boss,null);
 yield return new WaitForSeconds(1.55f);
 boss.enabled=false;
 record("boss_slam",Mathf.Abs(game.PlayerHealth.Current-72f)<0.1f,game.PlayerHealth.Current);
 yield return new WaitForSeconds(0.8f);
 game.PlayerHealth.Restore();animation.PlayIdle();player.InputEnabled=false;
 boss.enabled=true;countField.SetValue(boss,0);attackMethod.Invoke(boss,null);
 yield return new WaitForSeconds(1.22f);
 bool rolled=animation.TryPlayDodge();
 yield return new WaitForSeconds(0.25f);
 boss.enabled=false;
 record("dodge_invulnerability",rolled && game.PlayerHealth.Current==100f,new{rolled,hp=game.PlayerHealth.Current});
 yield return new WaitForSeconds(1f);
 animation.PlayIdle();game.PlayerHealth.Restore();player.InputEnabled=true;
 boss.enabled=true;countField.SetValue(boss,2);attackMethod.Invoke(boss,null);
 yield return new WaitForSeconds(2.05f);
 boss.enabled=false;
 record("boss_wave",Mathf.Abs(game.PlayerHealth.Current-78f)<0.1f,game.PlayerHealth.Current);
 yield return new WaitForSeconds(0.7f);
 game.PlayerHealth.TakeDamage(1000f);
 yield return new WaitForSeconds(0.1f);
 record("defeat",game.State==Cheon.Prototype.MountainPass.PassGameFlow.RunState.Defeat,game.State.ToString());
 game.RetryCheckpoint();
 yield return new WaitForSeconds(0.2f);
 record("retry",game.IsRunning && game.PlayerHealth.Current==100f && boss.Health.Current==420f,new{state=game.State.ToString(),hp=game.PlayerHealth.Current,bossHp=boss.Health.Current});
 game.BeginBossChallenge();boss.enabled=false;
 boss.Health.TakeDamage(10000f);
 yield return new WaitForSeconds(0.15f);
 record("victory",game.State==Cheon.Prototype.MountainPass.PassGameFlow.RunState.Victory,game.State.ToString());
 var report=new{checks,failures,complete=true,frame=Time.frameCount};
 System.IO.File.WriteAllText("Assets/Temp/MountainPrototype~/Test_CombatVerification.json",Newtonsoft.Json.JsonConvert.SerializeObject(report,Newtonsoft.Json.Formatting.Indented));
}
game.StartCoroutine(Routine());
return new{started=true};

