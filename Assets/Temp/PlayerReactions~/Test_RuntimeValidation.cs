var preview = UnityEngine.Object.FindFirstObjectByType<Cheon.Tests.PlayerReactions.Test_PlayerReactionPreview>();
if (preview == null) throw new Exception("테스트 씬 미실행");
preview.enabled = false;
var settings = preview.Settings;
var original = JsonUtility.ToJson(settings);
var results = new List<string>();
Action<bool,string> check = (condition,label)=> { if(!condition) throw new Exception("FAIL: " + label); results.Add(label); };
settings.heavyHit.startFrame = 3; settings.heavyHit.endFrame = 20; settings.heavyHit.speed = 0.5f;
preview.Play(Cheon.Tests.PlayerReactions.Test_PlayerReactionPreview.PreviewMode.HeavyOnly);
preview.AdvancePlayback(0.2f);
check(Mathf.Abs(preview.CurrentFrame - (3 + 0.2f * settings.heavyHit.FrameRate * 0.5f)) < 0.01f, "시작 프레임과 0.5배속 적용");
preview.SetPaused(true); float before = preview.CurrentFrame; preview.AdvancePlayback(0.5f);
check(preview.CurrentFrame == before, "일시정지 중 프레임 유지");
preview.StepFrame(0,1); check(Mathf.Abs(preview.CurrentFrame - (Mathf.Round(before)+1)) < 0.01f, "+1프레임 탐색");
preview.SetPaused(false); preview.AdvancePlayback(4f);
check(preview.Phase == Cheon.Tests.PlayerReactions.Test_PlayerReactionPreview.PreviewPhase.Complete && preview.CurrentFrame == 20, "종료 프레임에서 정확히 정지");
JsonUtility.FromJsonOverwrite(original, settings);
preview.Play(Cheon.Tests.PlayerReactions.Test_PlayerReactionPreview.PreviewMode.HeavyThenGetUp);
var phases = new List<string>();
for(int i=0;i<400;i++) { preview.AdvancePlayback(1f/60f); var phase=preview.Phase.ToString(); if(phases.Count==0||phases.Last()!=phase) phases.Add(phase); }
check(phases.Contains("HeavyHit") && phases.Contains("DownHold") && phases.Contains("GetUp") && phases.Last()=="Complete", "강피격 → 쓰러짐 유지 → 일어나기 → 대기 연결");
preview.repeatSequence = true;
preview.Play(Cheon.Tests.PlayerReactions.Test_PlayerReactionPreview.PreviewMode.Death);
for(int i=0;i<400;i++) preview.AdvancePlayback(1f/60f);
check(preview.Phase == Cheon.Tests.PlayerReactions.Test_PlayerReactionPreview.PreviewPhase.Dead && preview.IsPaused, "사망 후 자동 일어나기와 반복 방지");
float deathFrame=preview.CurrentFrame;
preview.AdvancePlayback(30f);
check(preview.CurrentFrame==deathFrame && preview.Phase==Cheon.Tests.PlayerReactions.Test_PlayerReactionPreview.PreviewPhase.Dead, "사망 마지막 자세 유지");
settings.heavyHit.speed=1.35f; preview.SaveSettings(); settings.heavyHit.speed=0.2f; preview.ReloadSettings();
check(Mathf.Abs(settings.heavyHit.speed-1.35f)<0.001f, "배속 저장 후 불러오기");
JsonUtility.FromJsonOverwrite(original, settings); preview.SaveSettings();
preview.repeatSequence = false; preview.ResetPreview(); preview.enabled=true;
return new {checks=results, phases, heavyFrames=settings.heavyHit.MaximumFrame, getUpFrames=settings.getUp.MaximumFrame, fps=settings.heavyHit.FrameRate, events=UnityEngine.Object.FindObjectsByType<UnityEngine.EventSystems.EventSystem>(FindObjectsSortMode.None).Length, buttons=UnityEngine.Object.FindObjectsByType<UnityEngine.UI.Button>(FindObjectsSortMode.None).Length};
