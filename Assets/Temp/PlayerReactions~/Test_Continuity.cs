var preview=UnityEngine.Object.FindFirstObjectByType<Cheon.Tests.PlayerReactions.Test_PlayerReactionPreview>();
preview.enabled=false;
preview.ResetPreview(); preview.Play(Cheon.Tests.PlayerReactions.Test_PlayerReactionPreview.PreviewMode.HeavyThenGetUp);
for(int i=0;i<200 && preview.Phase!=Cheon.Tests.PlayerReactions.Test_PlayerReactionPreview.PreviewPhase.DownHold;i++) preview.AdvancePlayback(1f/60f);
var hips=preview.CharacterAnimator.GetBoneTransform(HumanBodyBones.Hips);
var before=hips.position;
preview.AdvancePlayback(preview.Settings.downHoldSeconds+0.01f);
var after=hips.position;
float difference=Vector2.Distance(new Vector2(before.x,before.z),new Vector2(after.x,after.z));
if(difference>0.02f) throw new Exception("연결 시 골반 위치 이동: "+difference);
for(int i=0;i<10;i++)preview.AdvancePlayback(1f/60f);
preview.SetPaused(true);preview.enabled=true;
return new {transitionDelta=difference, before=before.ToString(),after=after.ToString(),root=preview.CharacterAnimator.transform.position.ToString(),phase=preview.Phase.ToString()};
